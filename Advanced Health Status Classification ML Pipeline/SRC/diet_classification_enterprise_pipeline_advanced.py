# ── Pairwise Cohen's d effect-size matrix (Fat(g), the top discriminator) ────
def cohens_d(a, b):
    n1, n2 = len(a), len(b)
    pooled_std = np.sqrt(((n1-1)*a.std(ddof=1)**2 + (n2-1)*b.std(ddof=1)**2) / (n1+n2-2))
    return (a.mean() - b.mean()) / (pooled_std + 1e-9)

