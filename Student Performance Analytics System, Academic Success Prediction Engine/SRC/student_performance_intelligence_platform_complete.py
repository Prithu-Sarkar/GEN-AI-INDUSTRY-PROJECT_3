# Effect Size Analysis - Cohen's d
print('\n' + '=' * 80)
print('EFFECT SIZE ANALYSIS: Cohens d for Key Comparisons')
print('=' * 80)

def cohens_d(group1, group2):
    '''Calculate Cohens d effect size'''
    n1, n2 = len(group1), len(group2)
    var1, var2 = np.var(group1, ddof=1), np.var(group2, ddof=1)
    pooled_std = np.sqrt(((n1-1)*var1 + (n2-1)*var2) / (n1+n2-2))
    return (np.mean(group1) - np.mean(group2)) / pooled_std if pooled_std > 0 else 0

# Gender differences
female_scores = df[df['gender'] == 'female']['overall_score']
male_scores = df[df['gender'] == 'male']['overall_score']
gender_d = cohens_d(female_scores, male_scores)

